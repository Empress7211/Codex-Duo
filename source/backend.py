def atomic_write(path: Path, data: str | bytes, mode: int = 0o600):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise UserError('拒绝覆盖符号链接文件：' + path.name)
    fd, name = tempfile.mkstemp(prefix='.' + path.name + '-', dir=path.parent)
    try:
        os.fchmod(fd, mode)
        with os.fdopen(fd, 'wb') as out:
            out.write(data.encode() if isinstance(data, str) else data)
            out.flush()
            os.fsync(out.fileno())
        os.replace(name, path)
    finally:
        if os.path.exists(name):
            os.unlink(name)


def write_json(path, value):
    atomic_write(path, json.dumps(value, ensure_ascii=False, indent=2) + '\n')


def toml_value(value):
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return '[' + ', '.join(toml_value(v) for v in value) + ']'
    if isinstance(value, dict):
        return '{' + ', '.join(toml_value(str(k)) + ' = ' + toml_value(v)
                               for k, v in value.items() if v is not None) + '}'
    if isinstance(value, (datetime.datetime, datetime.date, datetime.time)):
        return value.isoformat()
    raise UserError('配置包含无法序列化的值，未写入文件。')


def toml_dump(value):
    lines = ['# Generated by Codex 双开. Existing Codex / CC Switch are read-only.']
    def section(mapping, prefix):
        if prefix:
            lines.append('\n[' + '.'.join(toml_value(k) for k in prefix) + ']')
        for k, v in mapping.items():
            if not isinstance(v, dict) and v is not None:
                lines.append(toml_value(k) + ' = ' + toml_value(v))
        for k, v in mapping.items():
            if isinstance(v, dict):
                section(v, prefix + [k])
    section(value, [])
    result = '\n'.join(lines) + '\n'
    tomllib.loads(result)
    return result


