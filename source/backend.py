    def initialize(self):
        from history_store import initialize_shared, attach_home
        if (self.root / 'manifest.json').exists():
            manifest = self.owned()
            if 'profiles' not in manifest:
                manifest['profiles'] = self.profiles(manifest)
                write_json(self.root / 'manifest.json', manifest)
            if manifest.get('initialized'):
                return self.status()
        else:
            self.root.mkdir(parents=True, exist_ok=True, mode=0o700)
            os.chmod(self.root, 0o700)
            manifest = {'owner': 'codex-dual', 'schema': SCHEMA, 'root': str(self.root),
                        'initialized': False, 'created_at': time.time(), 'app': app_info(),
                        'protected_configs': fingerprints(self.source, self.cc)}
            manifest['profiles'] = self.profiles(manifest)
            write_json(self.root / 'manifest.json', manifest)
        initialize_shared(self.root)
        for item in self.profiles(manifest):
            p = item['id']
            self.home(p).mkdir(parents=True, exist_ok=True, mode=0o700)
            self.ui(p).mkdir(parents=True, exist_ok=True, mode=0o700)
            attach_home(self.root, self.home(p))
        self.sync_settings()
        manifest['initialized'] = True
        write_json(self.root / 'manifest.json', manifest)
        return self.status()

    def initialize_shared_workspace(self):
        """Create a new workspace on canonical history without importing it."""
        from managed_desktop import check_desktop_support
        from shared_store import canonical_paths, HISTORY_DIRS

        path = self.root / 'manifest.json'
        if path.exists():
            manifest = self.owned()
            if manifest.get('initialized'):
                if manifest.get('sync', {}).get('enabled'):
                    return self.status()
                raise UserError('已有旧工作区，请在设置中启用受管同步；不会覆盖旧历史。')
            if not manifest.get('direct_shared_init'):
                raise UserError('旧工作区初始化尚未完成，请先恢复原初始化。')
        else:
            paths = canonical_paths(self.source)
            for key in ('sqlite_home', *HISTORY_DIRS):
                target = paths[key]
                if not target.is_dir() or target == self.root or target.is_relative_to(self.root) or self.root.is_relative_to(target):
                    raise UserError('原生历史目录不可用或与工具工作区重叠：' + key)
            from history_store import count_threads
            if not (paths['sqlite_home'] / 'state_5.sqlite').is_file():
                raise UserError('原生会话数据库不存在，未创建工具工作区。')
            count_threads(paths['sqlite_home'])  # Read-only schema check; no history copy.
            self._common()  # Validate the inherited configuration before publishing ownership.
            current_app = app_info()
            check_desktop_support(APP)
            self.root.mkdir(parents=True, exist_ok=True, mode=0o700)
            os.chmod(self.root, 0o700)
            manifest = {'owner': 'codex-dual', 'schema': SCHEMA, 'root': str(self.root),
                        'initialized': False, 'direct_shared_init': True,
                        'created_at': time.time(), 'app': current_app, 'profiles': [],
                        'protected_configs': fingerprints(self.source, self.cc),
                        'sync': {**{key: str(value) for key, value in paths.items()},
                                 'version': 1, 'enabled': False, 'phase': 'preparing'}}
            write_json(path, manifest)
        for name in ('profiles', 'shared'):
            directory = self.root / name
            if directory.is_symlink():
                raise UserError('工具目录被重定向，未完成初始化：' + name)
            directory.mkdir(mode=0o700, exist_ok=True)
        # Prepare the local native copy only on the first actual launch.
        # Creating an empty workspace copies no desktop, SQLite, or rollouts.
        manifest['sync'].update(enabled=True, phase='ready', enabled_at=time.time(),
                                history_source='canonical')
        manifest['initialized'] = True
        write_json(path, manifest)
        return self.status()

    def _ensure_shared_skills(self):
        skill_source = self.source / 'skills'
        skill_target = self.root / 'shared/skills'
        if skill_source.exists() and not skill_target.exists():
            shutil.copytree(skill_source, skill_target, symlinks=False,
                            ignore=shutil.ignore_patterns('__pycache__', '.git', 'node_modules'))

    def _common(self):
        source_config = read_toml(self.source / 'config.toml')
        common = {k: copy.deepcopy(v) for k, v in source_config.items() if k in COMMON_KEYS}
        # Desktop regenerates these per-instance bridges on startup; copying
        # their old environment could point a new instance at the old service.
        for name in ('node_repl', 'cua_repl'):
            common.get('mcp_servers', {}).pop(name, None)
        # These redirects would escape the new profile or import host ownership.
        common.pop('shell_environment_policy', None)
        common['sqlite_home'] = str(self.history_sqlite())
        common['cli_auth_credentials_store'] = 'file'
        common['model_provider'] = 'custom'
        return common, source_config.get('model', 'gpt-6.1-sol')

    def create_profile(self, kind, name=None, provider_id=None):
        from history_store import attach_home
        from sidebar_store import seed_sidebar
        manifest = self.owned()
        self.require_upgrade_ready()
        if not manifest.get('initialized'):
            raise UserError('请先完成共享工作区初始化。')
        if kind not in ('api', 'subscription'):
            raise UserError('请选择 API 或订阅实例。')
        if provider_id and kind != 'api':
            raise UserError('订阅实例不能选择 API 供应商。')
        profiles = self.profiles(manifest)
        if name is not None and (not isinstance(name, str) or not name.strip() or len(name.strip()) > 80):
            raise UserError('实例名称需要为 1 到 80 个字符。')
        name = name.strip() if name else ('API 实例 ' if kind == 'api' else '订阅实例 ') + str(1 + sum(p['kind'] == kind for p in profiles))
        try:
            name = validate_display_name(name)
        except DesktopCopyError as error:
            raise UserError(str(error)) from error
        if provider_id and not any(p['id'] == provider_id and p['kind'] == 'api_key' for p in list_providers(self.cc)):
            raise UserError('请选择一个含 API key 的 CC Switch Codex 配置。')
        # Validate common TOML before registering a new instance. Existing
        # instances can keep running: only this new directory is written.
        common, model = self._common()
        profile_id = kind + '-' + uuid.uuid4().hex[:12]
        item = {'id': profile_id, 'kind': kind, 'name': name, 'ready': False, 'api_ready': False}
        manifest['profiles'] = profiles + [item]
        write_json(self.root / 'manifest.json', manifest)
        self.home(profile_id).mkdir(parents=True, exist_ok=True, mode=0o700)
        self.ui(profile_id).mkdir(parents=True, exist_ok=True, mode=0o700)
        attach_home(self.root, self.home(profile_id))
        if manifest.get('sync', {}).get('enabled'):
            from shared_store import attach_home as attach_canonical
            attach_canonical(self.root, self.home(profile_id), self.source)
        atomic_write(self.home(profile_id) / 'config.toml', toml_dump(self._profile_config(profile_id, common, model)))
        self._ensure_shared_skills()
        skill_target = self.root / 'shared/skills'
        if skill_target.exists():
            (self.home(profile_id) / 'skills').symlink_to(skill_target, target_is_directory=True)
        if (self.source / 'AGENTS.md').exists():
            atomic_write(self.home(profile_id) / 'AGENTS.md', (self.source / 'AGENTS.md').read_bytes())
        donor = next((self.home(p['id']) for p in profiles
                      if (self.home(p['id']) / '.codex-global-state.json').exists()), self.source)
        seed_sidebar(donor, self.home(profile_id))
        item['ready'] = True
        write_json(self.root / 'manifest.json', manifest)
        message = name + ' 已创建。订阅登录需在自己的新窗口中完成。'
        if provider_id:
            result = self.configure_api(provider_id, profile_id)
            if result.get('warning'):
                message += result['warning']
        return {'profile': self.profile(profile_id), 'message': message}

